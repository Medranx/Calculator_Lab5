    private void handleButton(String button) {
        switch (button) {
            case "C":
                clearAll();
                break;
            case "+":
            case "-":
            case "*":
            case "/":
                setOperator(button);
                break;
            case "=":
                calculateResult();
                break;
            case "+/-":
                plusOrMinus();
                break;
            default:
                enterNumber(button);
                break;
        }
    }

    private void enterNumber(String button) {
        String text = startNewNumber ? "0" : display.getText();

        if (button.equals(".")) {
            //so the number can have only one decimal point.
            if (!text.contains("."))
                display.setText(text + ".");
            else
                display.setText(text);
        } else if (text.equals("0")) {
        
            display.setText(button);
        } else if (text.equals("-0")) {
            display.setText("-" + button);
        } else {
            display.setText(text + button);
        }

        startNewNumber = false;
    }

    private void setOperator(String op) {
        if (!startNewNumber && pendingOp != null) {
            
            calculateResult();
        } else {
            storedValue = parseDisplay();
        }
        pendingOp = op;
        startNewNumber = true;
    }

    private void calculateResult() {
        if (pendingOp == null) {
            return;
        }
        double currentValue = parseDisplay();
        double result;

        switch (pendingOp) {
            case "+":
                result = storedValue + currentValue;
                break;
            case "-":
                result = storedValue - currentValue;
                break;
            case "*":
                result = storedValue * currentValue;
                break;
            case "/":
                if (currentValue == 0) {
                    JOptionPane.showMessageDialog(this,
                            "Cannot divide by zero.",
                            "Error", JOptionPane.ERROR_MESSAGE);
                    clearAll();
                    return;
                }
                result = storedValue / currentValue;
                break;
            default:
                result = currentValue;
        }
        display.setText(formatResult(result));
        storedValue = result;
        pendingOp = null;
        startNewNumber = true;
    }

    private double parseDisplay() {
        String text = display.getText();
        if (text.isEmpty() || text.equals("-") || text.equals(".") || text.equals("-."))
            return 0;
        return display.getValue();
    }

    private String formatResult(double result) {
        DecimalFormat format = new DecimalFormat("0.##########");
        return format.format(result);
    }

    private void clearAll() {
       
        display.setText("0");
        storedValue = 0;
        pendingOp = null;
        startNewNumber = true;
    }

    private void plusOrMinus() {
        String text = display.getText();
        if (text.startsWith("-"))
            display.setText(text.substring(1));
        else
            display.setText("-" + text);
        startNewNumber = false;
    }

